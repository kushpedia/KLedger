"""
Models for Tracking Generated Financial & Audit Report Exports (`apps.reports`).
"""
import uuid
from django.db import models
from apps.accounts.models import TenantScopedModel, VendorUser


class GeneratedReportArchive(TenantScopedModel):
    """
    Audit log of every PDF or Excel report generated by a vendor in the Reports & Exports Studio (`SCR-14`).
    """

    FORMAT_PDF = "PDF"
    FORMAT_EXCEL = "XLSX"

    FORMAT_CHOICES = (
        (FORMAT_PDF, "PDF Executive Document (.pdf)"),
        (FORMAT_EXCEL, "Excel Multi-Sheet Workbook (.xlsx)"),
    )

    report_code = models.CharField(max_length=40, db_index=True)
    report_title = models.CharField(max_length=160)
    store_scope_label = models.CharField(max_length=150)
    accounting_basis = models.CharField(max_length=25, default="CASH_FLOW")
    export_format = models.CharField(max_length=10, choices=FORMAT_CHOICES)
    generated_by = models.ForeignKey(VendorUser, on_delete=models.SET_NULL, null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]
        verbose_name = "Generated Report Archive"
        verbose_name_plural = "Generated Report Archives"

    def __str__(self):
        return f"{self.report_title} [{self.export_format}] — {self.store_scope_label}"
